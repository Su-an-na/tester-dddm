export function generateCandleData(basePrice: number, isPositive: boolean) {
  const count = 30;
  const candles = [];
  let prevClose = basePrice * (isPositive ? 0.96 : 1.04);

  for (let i = 0; i < count; i++) {
    const change = (Math.random() - (isPositive ? 0.44 : 0.56)) * (basePrice * 0.012);
    const open = prevClose;
    const close = Math.max(0.1, open + change);
    const high = Math.max(open, close) + Math.random() * (basePrice * 0.008);
    const low = Math.min(open, close) - Math.random() * (basePrice * 0.008);
    const volume = Math.floor(50000 + Math.random() * 250000);
    const day = (i + 1).toString().padStart(2, '0');
    
    candles.push({
      time: `08/${day}`,
      open: parseFloat(open.toFixed(2)),
      high: parseFloat(high.toFixed(2)),
      low: parseFloat(low.toFixed(2)),
      close: parseFloat(close.toFixed(2)),
      volume,
    });
    prevClose = close;
  }

  // Ensure last candle closes exactly at current basePrice
  candles[candles.length - 1].close = basePrice;
  candles[candles.length - 1].high = Math.max(candles[candles.length - 1].high, basePrice);
  candles[candles.length - 1].low = Math.min(candles[candles.length - 1].low, basePrice);

  return candles;
}

function generateChartData(basePrice: number, isPositive: boolean) {
  const points = 24;
  const data1D = [];
  let current = basePrice * (isPositive ? 0.985 : 1.015);
  
  for (let i = 0; i < points; i++) {
    const randomStep = (Math.random() - (isPositive ? 0.45 : 0.55)) * (basePrice * 0.004);
    current = Math.max(current + randomStep, basePrice * 0.85);
    const hour = (9 + Math.floor(i / 3)).toString().padStart(2, '0');
    const min = ((i % 3) * 20).toString().padStart(2, '0');
    data1D.push({ time: `${hour}:${min}`, value: parseFloat(current.toFixed(2)) });
  }
  // Ensure last point aligns with current price
  data1D[data1D.length - 1].value = basePrice;

  const data5D = Array.from({ length: 30 }, (_, i) => {
    const val = basePrice * (1 + (Math.sin(i / 4) * 0.03) + (isPositive ? (i / 30) * 0.04 : -(i / 30) * 0.04));
    return { time: `Day ${Math.floor(i / 6) + 1}`, value: parseFloat(val.toFixed(2)) };
  });

  const data1M = Array.from({ length: 22 }, (_, i) => {
    const val = basePrice * (1 + (Math.sin(i / 3) * 0.06) + (isPositive ? (i / 22) * 0.08 : -(i / 22) * 0.08));
    return { time: `Week ${Math.floor(i / 5) + 1}`, value: parseFloat(val.toFixed(2)) };
  });

  const data6M = Array.from({ length: 26 }, (_, i) => {
    const val = basePrice * (0.85 + (i / 26) * 0.25 + Math.random() * 0.04);
    return { time: `M${Math.floor(i / 4.3) + 1}`, value: parseFloat(val.toFixed(2)) };
  });

  const data1Y = Array.from({ length: 52 }, (_, i) => {
    const val = basePrice * (0.75 + (i / 52) * 0.35 + Math.sin(i / 5) * 0.05);
    return { time: `W${i + 1}`, value: parseFloat(val.toFixed(2)) };
  });

  const dataALL = Array.from({ length: 40 }, (_, i) => {
    const val = basePrice * (0.4 + (i / 40) * 0.7 + Math.sin(i / 4) * 0.08);
    return { time: `'${18 + Math.floor(i / 7)}`, value: parseFloat(val.toFixed(2)) };
  });

  return {
    '1D': data1D,
    '5D': data5D,
    '1M': data1M,
    '6M': data6M,
    '1Y': data1Y,
    'ALL': dataALL,
  };
}

